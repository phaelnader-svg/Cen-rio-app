-- Diagnóstico de registros ABERTOS afetados pela reformulação por remoção real — SOMENTE LEITURA.
-- Nada é encerrado, alterado ou apagado: só conta e descreve o tratamento que SERIA necessário
-- (rotina S9, que depende de autorização específica do dono). Sem dados pessoais: só contagens.
-- Uso: psql "$DATABASE_URL" -X -q -At -F'|' -v ON_ERROR_STOP=1 -f diagnostico-registros-abertos.sql
-- Saída: grupo|etapa|registro|abertos|tratamento proposto (não executado)
BEGIN TRANSACTION READ ONLY;
SET LOCAL statement_timeout = '60s';

SELECT * FROM (VALUES
  ('logistica', 'S6', 'retiradas em andamento (pickup_requests)',
   (SELECT count(*) FROM pickup_requests WHERE status IN ('AGUARDANDO_AGENDAMENTO','AGENDADA','EM_EXECUCAO','COM_OCORRENCIA')),
   'cancelar com motivo "retirada removida da operação"; peças passam a ser tratadas como "cliente traz"'),
  ('logistica', 'S6', 'retiradas realizadas e não recebidas (RETIRADA_REALIZADA)',
   (SELECT count(*) FROM pickup_requests WHERE status = 'RETIRADA_REALIZADA'),
   'manter como histórico; a chegada vira marcação opcional na OS (D1)'),
  ('logistica', 'S6', 'entregas da logística não concluídas (deliveries origin LOGISTICA)',
   (SELECT count(*) FROM deliveries WHERE origin = 'LOGISTICA' AND status IN ('PROVISORIA','AGENDADA','EM_TRANSPORTE','NO_DESTINO','FRUSTRADA')),
   'cancelar a entrega agendada; a peça volta a "pronta para entrega" para "Marcar como entregue" na OS'),
  ('logistica', 'S6', 'ocorrências logísticas abertas',
   (SELECT count(*) FROM logistics_occurrences WHERE status IN ('ABERTA','EM_TRATAMENTO')),
   'cancelar com motivo; bloqueio de expedição deixa de existir'),
  ('financeiro', 'S6', 'custos de viagem previstos ou devidos sem pagamento (logistics_costs)',
   (SELECT count(*) FROM logistics_costs WHERE status IN ('PREVISTO','DEVIDO')),
   'PREVISTO de viagem cancelada: cancelar; DEVIDO: manter e pagar pelo financeiro (conta a pagar) — decisão do dono'),
  ('financeiro', 'S6', 'contas a pagar de logística em aberto (account_payables LOGISTICA)',
   (SELECT count(*) FROM account_payables WHERE category = 'LOGISTICA' AND status IN ('ABERTO','PARCIAL')),
   'manter: pagamento normal pelo financeiro (não depende da tela de logística)'),
  ('financeiro', 'S6', 'cobranças com vencimento "na retirada" ainda abertas (D5)',
   (SELECT count(*) FROM customer_receivables WHERE due_trigger = 'RETIRADA' AND status IN ('ABERTO','PARCIAL')),
   'converter para vencimento por DATA com auditoria, regra a aprovar (não inventar datas)'),
  ('financeiro', 'S6', 'cobranças com vencimento "na entrega" ainda abertas',
   (SELECT count(*) FROM customer_receivables WHERE due_trigger = 'ENTREGA' AND status IN ('ABERTO','PARCIAL')),
   'manter: continuam vencendo pela entrega direta na OS'),
  ('compras', 'S4', 'pedidos de compra em aberto (RASCUNHO/CONFIRMADO/PARCIALMENTE_RECEBIDO)',
   (SELECT count(*) FROM purchase_orders WHERE status IN ('RASCUNHO','CONFIRMADO','PARCIALMENTE_RECEBIDO')),
   'RASCUNHO: cancelar; CONFIRMADO/PARCIAL: encerrar saldo com motivo (o recebido fica no histórico)'),
  ('compras', 'S4', 'chegadas físicas aguardando conferência (material_arrivals)',
   (SELECT count(*) FROM material_arrivals WHERE status = 'PENDENTE_CONFERENCIA'),
   'encerrar como "sem conferência formal"; o material vira item da lista simples/estoque simples se o dono quiser'),
  ('estoque', 'S4', 'reservas de estoque ativas (stock_reservations ATIVA)',
   (SELECT count(*) FROM stock_reservations WHERE status = 'ATIVA'),
   'liberar com motivo "reservas removidas"; nenhum saldo é alterado além do reservado'),
  ('medicoes', 'S3', 'medições pendentes ou em andamento',
   (SELECT count(*) FROM measurements WHERE status IN ('PENDENTE','EM_ANDAMENTO')),
   'cancelar com motivo; medidas técnicas passam a ser campos opcionais da peça (D8)'),
  ('medicoes', 'S3', 'solicitações de material não concluídas (material_requests)',
   (SELECT count(*) FROM material_requests WHERE status IN ('RASCUNHO','ENVIADA','EM_REVISAO','DEVOLVIDA')),
   'cancelar com motivo'),
  ('medicoes', 'S3', 'necessidades de material ativas (material_requirements ATIVA)',
   (SELECT count(*) FROM material_requirements WHERE status = 'ATIVA'),
   'manter como histórico (sem efeito: o bloqueio por material deixa de existir em S2)'),
  ('embalagem', 'S1', 'embalagens pendentes ou em andamento (packaging_records)',
   (SELECT count(*) FROM packaging_records WHERE status IN ('PENDENTE','EM_ANDAMENTO')),
   'cancelar com motivo "embalagem removida"; a peça passa a "pronta para entrega"'),
  ('embalagem', 'S1', 'peças paradas em AGUARDANDO_EMBALAGEM / EM_EMBALAGEM',
   (SELECT count(*) FROM service_order_items WHERE fulfillment_stage IN ('AGUARDANDO_EMBALAGEM','EM_EMBALAGEM')),
   'recalcular etapa sem embalagem → PRONTA_ENTREGA (com auditoria)'),
  ('embalagem', 'S1', 'tarefas de EMBALAGEM não concluídas',
   (SELECT count(*) FROM production_tasks WHERE activity = 'EMBALAGEM' AND status NOT IN ('CONCLUIDA','CANCELADA')),
   'cancelar com motivo'),
  ('producao', 'S2', 'tarefas bloqueadas por MATERIAIS',
   (SELECT count(*) FROM production_tasks WHERE 'MATERIAIS' = ANY(blockers) AND status NOT IN ('CONCLUIDA','CANCELADA')),
   'reavaliar liberação sem o bloqueio (o ciclo de 30 s já faz isso com a trava desligada)'),
  ('producao', 'S5', 'tarefas bloqueadas por PECA_NAO_RECEBIDA',
   (SELECT count(*) FROM production_tasks WHERE 'PECA_NAO_RECEBIDA' = ANY(blockers) AND status NOT IN ('CONCLUIDA','CANCELADA')),
   'reavaliar liberação sem o bloqueio (D1)'),
  ('comercial', 'S5', 'pedidos aguardando retirada ou chegada sem OS',
   (SELECT count(*) FROM commercial_orders o WHERE o.status IN ('AGUARDANDO_RETIRADA','RETIRADA_AGENDADA','RECEBIDO_PARCIAL')
      AND NOT EXISTS (SELECT 1 FROM service_orders s WHERE s.order_id = o.id)),
   'criar a OS do pedido fechado (D1), com auditoria'),
  ('ajuda', 'S7', 'pedidos de ajuda abertos (help_requests)',
   (SELECT count(*) FROM help_requests WHERE status IN ('PENDENTE','ATRIBUIDA','EM_EXECUCAO','ESCALADA')),
   'cancelar com motivo "pedidos de ajuda removidos" (D3); histórico preservado'),
  ('configuracao', 'S7', 'interruptores gravados (module_settings)',
   (SELECT count(*) FROM module_settings),
   'manter linhas (ignoradas pelo código novo); nenhuma alteração')
) AS t(grupo, etapa, registro, abertos, tratamento)
ORDER BY etapa, grupo;
ROLLBACK;
